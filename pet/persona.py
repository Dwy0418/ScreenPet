def absorb_format_block() -> str:
    return (
        "输出格式（每行都以「键名：」开头，一行一项，不要输出别的东西）：\n"
        "类型：" + "、".join(taste.GENRES) + " 里挑一个最贴近的（认不出来写「其他」）\n"
        "主题：一句话说清这是啥内容，尽量带上**台标/平台 + 节目名**"
        "（例如：浙江卫视《奔跑吧》第十四季，嘉宾刚进场就被罚）\n"
        "内容：2~3 句**具体**的——谁在跟谁做什么、刚才发生了什么、接下来大概会怎样"
        "（有连拍就对照着写）；**不许写「画面展示了…」「展现了一个…」「这是一段…」"
        "这种笼统概括**，那不是内容，是把画面翻译成说明书\n"
        "玩法：**是游戏**才写（怎么玩的：搜刮跑毒 / 抽卡养成 / 五对五拆塔…），"
        "不是游戏一律写「未知」；看不清玩法也别猜\n"
        "画风：**是游戏**才写（画面什么风格：写实军武 / 像素 / 二次元 / 水墨…），"
        "说不准就写「未知」\n"
        "玩家群体：**是游戏**才写，一句话——这游戏平常都是谁在玩（硬核老玩家 / 学生党 / "
        "休闲向 / 怀旧党…），看不出来写「未知」\n"
        "看点：最值得聊的一个点（笑点 / 槽点 / 爽点 / 疑点，只说一个）\n"
        "高光：这一支**接下来最值得等的那一下**——要具体到谁要做什么、大概到哪儿会出"
        "（开大 / 拆塔 / 反杀 / 反转 / 名场面 / 笑点炸出来 / 关键台词…），"
        "实在看不出来写「未知」；别写「会很精彩」这种空话\n"
        "人物：画面里的人或角色，认不出就写「未知」\n"
        "地点：直播间 / 游戏地图 / 教室 / 厨房…看不出来就写「未知」\n"
        "互动：点赞=是/否｜收藏=是/否｜关注=是/否｜评论=是/否"
        "（看右侧／右下角那几个按钮亮不亮、有没有「已关注」「已收藏」，看不清一律写「否」）\n"
        "关键词：用、隔开的 3~6 个词（台标、节目名、人物名、话题标签都算），方便以后翻记录\n"
        "每一项都短一点，别超过一句话。"
    )


def absorb_prompt(
    cfg,
    ocr_text: str = "",
    window: str = "",
    clock: str = "",
    frames: int = 1,
    previous: str = "",
) -> str:
    """看片笔记那一轮的 user 消息：几点 + 窗口 + 画面文字 + 上一遍记了什么 + 格式要求。"""
    blocks: List[str] = []
    blocks += _now_block(clock, window, ocr_text)
    if previous:
        blocks.append("【你上一遍记下来的（这一眼更靠后，读完把不准的地方改掉）】\n" + previous)
    if previous:
        head = (
            "这是同一支视频往后几秒的画面——对照着看它**在演什么**，"
            "把笔记更新得更准（格式照旧；游戏类的玩法 / 画风 / 玩家群体也要接着给）。\n\n"
        )
        view = ""
    else:
        head = "这是刚刚刷出来的画面（大概率是一支新视频 / 新场景）。把这一眼读明白。\n\n"
        view = _view_note(frames)
    blocks.append(view + head + absorb_format_block())
    return "\n\n".join(blocks)


