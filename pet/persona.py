def _now_block(clock: str = "", window: str = "", ocr_text: str = "") -> List[str]:
    lines: List[str] = []
    if clock:
        lines.append(f"现在时间：{clock}")
    if window:
        lines.append(f"窗口：{window}")
    if ocr_text:
        lines.append(
            "画面上的文字与关键信息。前面那段以「画面关键信息」开头的，是本地从这些字里"
            "认出来的（台标 / 平台 / 节目名 / 集数 / 话题人名），**优先信它**；"
            "它后面才是原始识别文字（弹幕/字幕/按钮混在一起，噪声多，挑有用的当素材，不要照念）：\n"
            + ocr_text
        )
    return ["【现在】\n" + "\n".join(lines)] if lines else []


def _history_block(cfg, history: Sequence[str]) -> List[str]:
    """刚说过的话：只用来"别再重复"。

    以前这里只写"这次别再重复上面说过的意思"，小模型会把上面那几句**原样抄回来**
    当台词（现场日志：`[noise] 模型把提示词抄回来了，这句丢掉：[开心] 这球才15？ / 就这？`
    ——抄的正是这一块），抄回来的又会被噪音闸丢掉，看着就是"它一直不说话"。
    所以现在把话说明白：这些字是给你避开的、不是台词；想不出新角度就交 [沉默]。
    """
    if not history:
        return []
    limit = max(1, int(cfg.capture.history_size))
    return [
        "【你刚才说过】\n"
        + "\n".join(list(history)[-limit:])
        + "\n（这些是你自己的原话，只给你避开用，一个字都不要再写出来；"
        "换个新角度说一句，想不出新的就把第一行写成 [沉默]）"
    ]


def _scene_block(scene: str) -> List[str]:
    """上一眼的场景：**只提醒"这一幕你说过了"，不把 5W1H 原文塞回去**。

    以前是把原文整段回喂，结果小模型会把它抄回来当第二行——现场日志里同一个
    "人物=玩家；事件=…教学 场景" 反复出现（还是上一支视频的场景），第一行却空着。
    想看它上一眼到底看明白什么，日志里有 `[scene]` 那行，不必再喂给它。
    """
    if not (scene or "").strip():
        return []
    return [
        "【提醒】这一幕你上一眼已经看过、也说过一句了：别重复刚才那个说法——"
        "换个角度，或者第一行写 [沉默]。"
    ]


def _watch_block(watch: str) -> List[str]:
    """看片笔记：视频一刷出来它就完整读过一遍，用户提问时按相关度挑几条回喂。"""
    text = (watch or "").strip()
    if not text:
        return []
    return [
        text
        + "\n上面这些是**你自己看的时候记下的**，跟问的事有关就直接用里面的细节回答；"
        "真没有的话就说没注意，别编。"
    ]


def _chat_block(cfg, chat_history) -> List[str]:
    rows = [(q, a) for q, a in (chat_history or []) if q or a]
    if not rows:
        return []
    limit = max(1, int(getattr(cfg.chat, "history_size", 6)))
    lines = [f"用户：{q}" + (f"\n你：{a}" if a else "") for q, a in rows[-limit:]]
    return ["【你俩刚聊过】\n" + "\n".join(lines)]


def user_prompt(
    cfg,
    history: Sequence[str] = (),
    ocr_text: str = "",
    window: str = "",
    memory: str = "",
    clock: str = "",
    scene: str = "",
    watch: str = "",
    taste: str = "",
    episode: str = "",
    frames: int = 1,
    insist: bool = False,
) -> str:
    """拼装这一帧的全部上下文：记忆背景 + 口味 + 上一眼的场景 + 看片笔记 + 窗口 + 画面文字 + 刚说过的话。

    insist=True 是"补说"那一轮（上一轮它只交了场景行 / 把画面上的字抄回来了）：
    这一轮把话说死——必须给出第一行台词，别再复述上下文。
    """
    blocks: List[str] = []
    blocks += _memory_block(memory)
    blocks += _taste_block(taste)
    blocks += _scene_block(scene)
    blocks += _watch_block(watch)
    blocks += _episode_block(episode)
    blocks += _now_block(clock, window, ocr_text)
    blocks += _history_block(cfg, history)
    if insist:
        tail = (
            _view_note(frames)
            + "这一轮**只回一句话**——就是你现在想说出嘴的那句台词（可以带 [情绪] 标签），"
            "短一点、口语一点，「哈哈」「啊？」「这波稳了」都行，写完就结束。\n"
            "说**你自己那一下的想法或反应**就行：不许描述画面、不许推测他们在干嘛、"
            "不许出现「似乎 / 好像 / 看样子 / 应该是在」这类词——你是一起看的人，不是解说。\n"
            "不要写场景行，也不要写任何别的行、不要解释、不要复述上面任何一段背景——"
            "上一轮你要么只交了场景行、要么写成了画面解说，这一轮只要那句台词。"
        )
    else:
        tail = (
            _view_note(frames)
            + "先在心里过一遍 Who/What/When/Where/Why，再按两行格式回我"
            "（第一行必须有台词；真没话说才只回 [沉默]）。"
        )
    blocks.append(tail)
    return "\n\n".join(blocks)


# 他这句话是冲**谁**说的：问桌宠自己 / 只是打个招呼。这两类最容易答非所问——
# 现场（用户截图）就出过：用户说「你好」，它回「这集都第28集了」；用户问「你在干嘛呢」，
# 它把话原样抛回来「他在干嘛呢？」。判据只用本地关键词（跟 dialog.py 一个路子，
# 不联网、不花钱），认出来就在这一轮的提示词里把话说死。
_SELF_MARKS: Tuple[str, ...] = (
    "你在干嘛", "你在干什么", "你在做什么", "你在忙什么", "在干嘛呢", "在干嘛", "你干嘛",
    "你是谁", "你叫什么", "你几岁", "你多大", "你累不累", "你困不困", "你饿不饿",
    "你还好吗", "你好吗", "你在不在", "你睡了吗", "你还在吗",
)
_GREET_MARKS: Tuple[str, ...] = (
    "你好", "您好", "嗨", "哈喽", "哈啰", "早上好", "早安", "中午好", "下午好", "晚上好",
    "在吗", "好久不见",
)
# 英文招呼单独用词边界认：直接用 `in` 的话，「this」里也藏着 hi
_EN_GREET = re.compile(r"\b(hi|hello|hey|yo)\b")


def user_focus_note(user_text: str) -> str:
    """他这句话是冲**他自己**来的吗——认出来就补一句「该怎么接」的叮嘱。

    两类最容易翻车：

    * **问桌宠自己的近况**（「你在干嘛呢」）：得用「我」回它自己在干嘛，不能答成
      「他 / 画面里的人」，更不能把他的问句换个字抛回去；
    * **只是打个招呼**（「你好」）：回一句招呼就行，别把正在看的剧透一遍。

    返回空串 = 没认出来，什么都不加（宁可不说，也别把正常问题当成寒暄）。
    """
    body = (user_text or "").strip()
    if not body:
        return ""
    if any(mark in body for mark in _SELF_MARKS):
        return (
            "\n⚠ 他这句问的是**你自己**（你是个桌宠）：用「我」的口吻如实回你自己这会儿在干嘛"
            "（比如「我正陪你看画面呢」），**不要**答成「他 / 画面里的人」，"
            "也不要把他的问句换个字抛回去（「他在干嘛呢」这种等于没答）。"
        )
    if any(mark in body for mark in _GREET_MARKS) or _EN_GREET.search(body.lower()):
        return (
            "\n⚠ 他这句只是跟你打个招呼：回一句热情的招呼、顺口接个话头就行，"
            "**别**把你正在看的视频内容端出来——他是跟你打招呼，不是问剧情。"
        )
    return ""


def chat_user_prompt(
    cfg,
    user_text: str,
    history: Sequence[str] = (),
    chat_history=(),
    ocr_text: str = "",
    window: str = "",
    memory: str = "",
    clock: str = "",
    scene: str = "",
    watch: str = "",
    taste: str = "",
    episode: str = "",
    frames: int = 1,
    comfort: bool = False,
    dialog_hint: str = "",
) -> str:
    """用户直接说话那一轮：把"他说了什么"摆最显眼的位置，让模型正面接话。

    comfort=True 是他这一句在诉苦：这一轮只要安慰 + 抱抱，别接梗、别讲道理。
    dialog_hint 是这一句的类型提醒（记录/分析/学习，见 pet/dialog.py）：
    问句就先把答案给清楚，带情绪就先跟着他的情绪走——只在这轮提示词里出现。
    """
    blocks: List[str] = []
    blocks += _memory_block(memory)
    blocks += _taste_block(taste)
    blocks += _watch_block(watch)
    blocks += _episode_block(episode)
    blocks += _scene_block(scene)
    blocks += _chat_block(cfg, chat_history)
    blocks += _now_block(clock, window, ocr_text)
    blocks += _history_block(cfg, history)
    if comfort:
        ask = (
            "他现在心里不好受，跟你说这些是想让你陪一下。"
            "先接住他的情绪，再抱抱他（顺口一句「抱抱」就行）；"
            "不要讲道理、不要给建议、不要提屏幕上的东西。1~2 句，短。"
            "最后按格式附上场景行。"
        )
    else:
        ask = (
            "现在**回他这一句**：1~2 句、口语、别沉默。\n"
            "他是**跟你说话**（他嘴里的「你」就是你自己，不是画面里的人、也不是他主人），"
            "先直接答他说的这件事；他要是打招呼 / 跟你闲聊，就正常接话，"
            "**别**拐去讲你正在看的视频。\n"
            "**只有他明确问画面 / 视频里的事**（这剧好看吗、刚才那人是谁），才去翻上面"
            "【你刚看完的视频】【看片记录】拿具体细节答；找不到就直说没注意。\n"
            "最后按格式附上场景行。"
        )
        focus = user_focus_note(user_text)
        if focus:
            ask = ask + focus
        if dialog_hint:
            ask = ask + "\n" + dialog_hint
    blocks.append(_view_note(frames) + "【用户跟你说】\n" + (user_text or "").strip() + "\n\n" + ask)
    return "\n\n".join(blocks)


def _content_ask(kind: str, note: str, topic: str, frames: int = 1) -> str:
    """按"他正在干嘛"主动夸 / 主动关心那一轮的叮嘱（见 proactive._content_nudge）。

    topic 是那件事的具体名字（《奔跑吧》第九季 / 王者荣耀 / 那份文档），note 是
    "他已经看/打/忙了 N 分钟"。夸要夸在**他正在做的这件事**上，关心也要落在**这件事**上
    ——"你真棒"和"记得喝水"这种放之四海皆准的话，等于没看见他。
    """
    who = topic or "他正在看的那个东西"
    if kind == proactive.PRAISE:
        return (
            _view_note(frames)
            + f"【现在轮到你去夸他】{note or '他在同一件事上已经待了一会儿'}。\n"
            f"他这会儿在：{who}。\n"
            "要夸的是**屏幕前这个人**（画面里的明星、主播、角色再可爱也不是夸的对象），"
            "而且要夸在**他正在做的这件事**上：\n"
            "· 他在看视频/剧 → 夸他挑内容的眼光、他看这段时的反应、他找片子的本事；\n"
            "· 他在打游戏 → 夸他刚才那一下操作、这个思路、他这一局的稳；\n"
            "· 他在忙活/干活 → 夸他这个人：做得细、坐得住、这股劲儿。\n"
            "要求：\n"
            "· 挑一个**具体的点**夸，别空喊「你最棒」；一句到两句，短、口语、带情绪。\n"
            "· 不许「不过」「但是」「虽然」，不许先夸后贬，不许谦虚往回找补。\n"
            "· 别报告时间（不要说你看了/坐了多久），也别提「我一直在看你」。\n"
            "**这一轮只回一句话**（就是你夸他的那句），不要写场景行、不要写别的行；"
            "不能回 [沉默]。"
        )
    return (
        _view_note(frames)
        + f"【现在轮到你去关心他】{note or '他在同一件事上坐太久了'}。\n"
        f"他这会儿在：{who}。\n"
        "这一轮做两件事，一句到两句就够：\n"
        "· 先关心他的**身体**（坐太久、一直盯屏幕、肩膀/腰/脖子/眼睛，挑一个说，别念清单）；\n"
        "· 再针对**他正在做的这件事**给一句能落地的小建议：看剧的让他歇一集、"
        "打游戏的让他打完这局就起来、忙活的让他存个盘伸个懒腰——别讲大道理、别写成健康手册。\n"
        "· 语气是熟人唠叨，不是客服提醒；别报告时间（不要说「你坐了 50 分钟」）。\n"
        "必须说一句话，不能回 [沉默]；按两行格式回（第二行还是场景）。"
    )


def proactive_prompt(
    cfg,
    kind: str,
    note: str = "",
    history: Sequence[str] = (),
    ocr_text: str = "",
    window: str = "",
    memory: str = "",
    topic: str = "",
    clock: str = "",
    scene: str = "",
    watch: str = "",
    taste: str = "",
    episode: str = "",
    frames: int = 1,
) -> str:
    """主动搭话那一轮的 user 消息：上下文和平时一样，只是换个由头、不许沉默。

    topic 是它自己翻长期记忆挑出来的话头（"他最近老在看「王者荣耀」"），
    只当素材用，别让它把这句话原样念一遍。
    """
    blocks: List[str] = []
    blocks += _memory_block(memory)
    blocks += _taste_block(taste)
    blocks += _watch_block(watch)
    blocks += _episode_block(episode)
    blocks += _scene_block(scene)
    blocks += _now_block(clock, window, ocr_text)
    blocks += _history_block(cfg, history)

    if kind in (proactive.PRAISE, proactive.CARE_TOPIC):
        # 按"他正在干嘛"夸 / 关心：夸要夸在具体这件事上，关心也要落在具体这件事上
        blocks.append(_content_ask(kind, note, topic or "", frames))
        return "\n\n".join(blocks)

    detail = f"（{note}）" if note else ""
    ask = (
        _view_note(frames)
        + f"【现在轮到你主动开口】{proactive.REASONS.get(kind, '你想主动说点什么')}{detail}。\n"
        "这次的重点不是吐槽画面，而是主动跟屏幕前这个人搭话："
        "说说你的感受、问他一句、或者单纯逗他一下都行。\n"
    )
    if topic:
        ask += (
            f"另外，你记得这事：{topic}。"
            "可以拿它当话头（像熟人那样随口提一句，别原样念出来，也别硬扯）。\n"
        )
    ask += "必须说一句话，不能回 [沉默]；按两行格式回（第二行还是场景）。"
    blocks.append(ask)
    return "\n\n".join(blocks)


def spotlight_prompt(
    cfg,
    kind: str,
    note: str = "",
    action: str = "",
    history: Sequence[str] = (),
    ocr_text: str = "",
    window: str = "",
    memory: str = "",
    clock: str = "",
    scene: str = "",
    watch: str = "",
    taste: str = "",
    episode: str = "",
    frames: int = 1,
) -> str:
    """两个"必须开腔"的场合：刚刷到新视频 / 他刚点赞收藏关注。

    跟主动搭话的区别：这两件事本身就是由头，不用寒暄、不用说"我来陪你看看"，
    直接顺着这件事接一句——像群聊小助手，有料就接，短、快、带梗。
    """
    blocks: List[str] = []
    blocks += _memory_block(memory)
    blocks += _taste_block(taste)
    blocks += _watch_block(watch)
    blocks += _episode_block(episode)
    blocks += _scene_block(scene)
    blocks += _now_block(clock, window, ocr_text)
    blocks += _history_block(cfg, history)

    if kind == "action":
        head = (
            f"【他刚动手了】他刚在这支视频上{action or '动了手'}——这是他自己点的，不是你看出来的。\n"
            "就着这件事说一句：可以起哄、可以问他一句、也可以顺手记一笔「原来他吃这套」。\n"
            "别写成道贺（「恭喜你」「给你点赞」这种客服腔一律不准），也别复述你在做什么。\n"
        )
        if note:
            head += f"这支视频是：{note}\n"
    else:
        head = "【刚刷到一支新的】这一眼你已经读过一遍、记下来了，下面是你的笔记。\n"
        if note:
            head += note + "\n"
        head += (
            "现在马上接一句：像群里手最快的那个人，看准了就开腔——"
            "挑一个具体的点说（谁在干嘛、这话接得妙不妙、接下来会怎样），别扫一眼就夸好看。\n"
            "笔记里写了「高光」就**优先拿它开腔**：可以像「前方高能」那样先甩一句预告"
            "（预告要具体到人和动作，别只喊口号），也可以就着它起哄、押一句、"
            "或者问一句「你猜他下一步干嘛」——这是提前说话，不是事后总结。\n"
        )

    ask = (
        _view_note(frames)
        + head
        + "必须给出一句话，不能回 [沉默]；最多两句，按两行格式回（第二行还是场景）。"
        "不许用「我来陪你看看」「一起看看」这种寒暄开场。"
    )
    blocks.append(ask)
    return "\n\n".join(blocks)


