# ---- 气泡里允许出现的标点 ------------------------------------------------
# 只有这几种：，。？！…，引用用 “” 和书名号《》。动作描写用的（）也留着
# ——人设里本来就要求它用「（抱住你）」这种方式比划动作，那不是"多余的符号"。
# 表情符号（❤ 这类）也留着：本地那几句「抱抱收到啦 ❤」是有意写暖的。
KEEP_MARKS = "，。？！…“”《》（）"
_EMOJI = re.compile("[\u2600-\u27bf\u2b00-\u2bff\ufe0f\U0001f000-\U0001faff]")
# 别的写法先归一成上面那几种（顿号、分号、冒号一律当逗号）
_MARK_ALIASES = (
    (",", "，"), ("、", "，"), (";", "，"), ("；", "，"), ("：", "，"), ("﹑", "，"),
    ("?", "？"), ("!", "！"), ("(", "（"), (")", "）"),
)
# 模型拿不定主意时会把两三句**备选台词**用「/」并列着交上来。现场那句气泡就是：
#     这波稳了 / 这画面，高启强这表情，感觉他要发火了！ / 你得服从指挥吧你得接受
# 那不叫说话，是在给程序挑。所以先在「/」处切一刀，只念第一句。
_ALT_SPLIT = re.compile(r"\s*[/／|｜]+\s*")
_DOT_RUN = re.compile(r"\.{2,}|。{2,}|·{2,}")
# 句首那个 [情绪] / [沉默] 标签是留给 mood.split_mood 剥的：它是"半个方括号"，
# 别在这里当多余符号一起清掉（清掉之后 mood 就认不出它了）。
_LEAD_TAG = re.compile(r"^\s*[\[【(（]\s*[^\]】)）]{1,8}\s*[\]】)）]\s*")


def tidy_marks(text: str) -> str:
    """把一句话的标点收拾成"气泡里该有的样子"。

    只留 ，。？！… 和 “”《》（）以及表情符号；别的符号（/ ｜ ~ # * — ≥ 之类）全部清掉。

    为什么非要在程序这一侧动手：模型有个改不掉的毛病——**拿不定主意就把几句备选并列着写**，
    屏幕上立刻变成「A / B / C」一串。提示词里说归说，真漏出来还得靠这里兜住。
    """
    out = (text or "").strip()
    if not out:
        return ""
    tag = ""
    lead = _LEAD_TAG.match(out)
    if lead:                       # 句首的情绪标签原样端过去，别的照常收拾
        tag, out = out[: lead.end()], out[lead.end():]
    out = _ALT_SPLIT.split(out)[0].strip()          # 「/」后面是它自己没定下来的备选
    out = _DOT_RUN.sub("…", out)                     # 「...」「。。。」统一成 …
    out = re.sub(r"(?<=\d)\.(?=\d)", "\x00", out)    # 数字里的小数点先藏起来
    for old, new in _MARK_ALIASES:
        out = out.replace(old, new)
    out = "".join(
        ch
        for ch in out
        if ch.isalnum() or ch in KEEP_MARKS or ch in " \x00" or _EMOJI.match(ch)
    )
    out = out.replace("\x00", ".")
    out = re.sub(r"，{2,}", "，", out)
    out = re.sub(r"。{2,}", "。", out)
    out = re.sub(r"…{2,}", "…", out)
    out = re.sub(r"！{3,}", "！！", out)
    out = re.sub(r"？{3,}", "？？", out)
    out = re.sub(r"，+(?=[。？！…])", "", out)        # 「，。」→「。」
    out = re.sub(r"(?<=[。？！…])，+", "", out)       # 「。，」→「。」
    out = re.sub(r"[ \t]{2,}", " ", out)
    return (tag + out.strip(" ，。")).strip()


def fit(text: str, limit: int) -> str:
    """太长就在最近的句读处断开，别把句子从中间劈开（气泡里读着才不别扭）。"""
    line = (text or "").strip()
    if limit <= 0 or len(line) <= limit:
        return line
    head = line[:limit]
    cut = max(head.rfind(ch) for ch in "，。？！…")
    if cut >= max(4, limit // 2):
        head = head[:cut]
    return head.rstrip(" ，。") + "…"


def _avoid_section(avoid) -> str:
    """「刚说过这些，别再重复」——提示词里再加一道闸（worker 那边还有相似度兜底）。"""
    block = humanstyle.avoid_block(avoid)
    return ("\n" + block + "\n") if block else ""


def _banned_section() -> str:
    """不许出现的书面词/文案腔（内置一份，加 `data/chat_style.json` 里你自己补的）。"""
    words = "、".join(humanstyle.banned())
    return f"禁止出现的词（出现一次就算说错）：{words}。\n" if words else ""


def _view_note(frames: int = 1) -> str:
    """告诉模型这一轮看到的是一张静图，还是一排连拍。"""
    count = int(frames or 1)
    if count > 1:
        return (
            f"这是你最近 {count} 眼的**连拍**：同一张图里从左到右按时间先后排，中间有细黑缝。"
            "先对比这几张看出**在发生什么**（谁做了什么、进度到哪了、话头怎么接的），"
            "再说你的反应；别把每一张都描述一遍。\n"
        )
    return "这是刚刚的屏幕画面。\n"


def format_block(allow_silence: bool = True) -> str:
    """两行输出格式：第一行台词，第二行 5W1H 场景。

    这里连着踩过两个坑：最早写的是「真没话说才写 [沉默]，而且不要写场景行」，小模型把这个
    和「必须是这两行」揉在一起，就变成**只交第二行场景、第一行空着**；把沉默也改成
    "第一行写 [沉默]" 之后，它不想说话时**照样**拿第二行交差（现场日志里一片
    「模型只回了场景没给台词」）。所以现在两件事一起做：沉默必须落在第一行（[沉默]），
    第二行降级成"想起来就写、可有可无"——没有哪一行是非交不可的，它就没理由只交场景行。

    第三个坑更隐蔽：**别在这里放"现成的例句"**。以前写着「例如「[无语] 这操作我真看不懂」」
    和「场景：人物=黑衣男主播｜事件=连抽十次没出金色｜…抽卡直播间…」，小模型会把它们
    原样抄回来——抄例句当台词（被噪音闸丢成静音），抄示例场景当自己的场景（屏幕上明明是
    《英雄联盟》直播间，它报的是"抽卡直播间"）。所以现在只给骨架，一句可抄的成品都不给。

    第四个坑是"骨架本身也被抄"：现场气泡里出过
    `这画面还挺酷的 / 场景：人物｜事件｜时间｜地点｜原因`——它把第二行的**格式清单**当内容交了上来。
    所以这里明说「这几个词只是告诉你按什么顺序写，一个都不许原样写进去」，
    解析侧（scene.py）也把骨架当"没看出来"丢掉，两头都堵住。
    """
    if allow_silence:
        first = (
            "第一行：情绪标签 + 一句台词。情绪标签从 [开心] [无语] [激动] [吐槽] [好奇] 里挑一个"
            "放在最前面。**这一行必须有**——不想开口也要写（写 [沉默] 三个字），不允许空着。\n"
        )
        second = (
            "第二行（想起来就写，可有可无）：一句以「场景：」开头的备注，"
            "按 人物、事件、时间、地点、原因 的**顺序**，一个短句接一个短句写下去，"
            "之间用一个「｜」隔开；哪一项没看出来就空着（两个「｜」挨着），不许硬编。\n"
            "⚠ 「人物」「事件」「时间」「地点」「原因」这几个词只是**告诉你按什么顺序写**，"
            "**一个都不许原样写进去**——第二行要写的是你看到的内容，不是这张格式清单。\n"
        )
        tail = (
            "两个坑必须避开：① 不想开口就把第一行写成 [沉默]；"
            "② 输出里绝对不许出现\"只有场景行、没有第一行\"——第二行只是备注，不是回答。\n"
            "只要这一眼有具体内容（谁做了什么、说了什么、进度到哪），第一行就说一句——"
            "短到「哈哈」「就这」也行。"
        )
    else:
        first = (
            "第一行：情绪标签 + 一句台词。情绪标签从 [开心] [无语] [激动] [吐槽] [好奇] 里挑一个"
            "放在最前面。\n"
        )
        second = (
            "第二行：一句以「场景：」开头的备注，按 人物、事件、时间、地点、原因 的**顺序**，"
            "一个短句接一个短句写下去，之间用一个「｜」隔开；哪一项没看出来就空着"
            "（两个「｜」挨着），不许硬编。\n"
            "⚠ 「人物」「事件」「时间」「地点」「原因」这几个词只是**告诉你按什么顺序写**，"
            "**一个都不许原样写进去**——第二行要写的是你看到的内容，不是这张格式清单。\n"
        )
        tail = (
            "注意：第二行的场景写的是**屏幕画面**本身，不是你俩的对话，更不是这场聊天；"
            "它是留给程序归档的备注，所以**第一行那句话不必跟它对得上**——"
            "你嘴上想说什么就说什么，不用为了照顾第二行把话写完整。"
        )
    head = (
        "输出格式（第一行必须有；第二行可有可无，别为了它把第一行丢了）：\n"
        if allow_silence
        else "输出格式（必须是这两行，不要输出别的东西）：\n"
    )
    # 这条是"念屏幕 / 抄块头"的总闸：现场真的出过一句
    # `画面关键信息：第孬期 . / > 0 收/A《抖音 ×/ 第集：`——它把 OCR 碎片拼了一串、
    # 还带着提示词的块头名，直接摆到用户脸上。所以这里把形状说死。
    shape = (
        "③ 台词里**不许出现提示词里的块头名**（「画面关键信息」「【现在】」「【看片笔记】」"
        "「场景」这类字样，一个都不许当开头），也**不许把屏幕上的文字、数值、符号拼成一串念出来**"
        "（比如「第28集 / > 0 收 / ×」这样）——那不是说话，那是抄屏幕。"
        "想提画面上的字就说人话：「这集都第28集了」「这进度条卡半天了」。\n"
        "④ 第二行也一样：**不许把「人物｜事件｜时间｜地点｜原因」这张清单原样抄一遍**——"
        "那是格式说明，不是你看出来的内容；看不出来就空着。\n"
    )
    return head + first + second + tail + shape


def system_prompt(
    cfg,
    proactive: bool = False,
    avoid=(),
    insist: bool = False,
    kind: str = "",
) -> str:
    """陪看时的系统提示词（默认人设，cfg.system_prompt 写了就听用户的）。

    kind 是这一轮的由头（proactive.py 里那几个）——不同由头会追加不同的叮嘱。
    """
    if cfg.system_prompt.strip():
        base = cfg.system_prompt.strip()
    else:
        p = cfg.persona
        base = (
            f"你叫「{p.name}」，是一个住在用户电脑屏幕边上的陪伴小精灵。"
            f"你的性格：{p.style}。\n"
            "用户会每隔几秒把当前屏幕画面（通常是他在看的视频/直播/游戏）截一张图给你，\n"
            "你要像一个坐在旁边一起看的人那样，先看准画面，再冒出一句自己的看法。\n"
            + _OBSERVE_BLOCK
            + "硬性要求：\n"
            f"1. 每次只说一句话，不超过 {p.max_chars} 个字，口语化、有情绪，别像解说员。\n"
            "2. 不要复述画面里已经写着的文字/字幕/按钮，不要解释你看到了什么。\n"
            "3. 不要每次都说话。画面平淡、重复、看不懂、或者跟你刚说过的话意思差不多时，"
            "只回复 [沉默]。\n"
            "4. 不要用「我看到了」「这张图里」这类旁观者口吻，直接说你的反应。\n"
            "5. 可以毒舌、可以开玩笑，但不说脏话、不涉及真实人物的恶意攻击。\n"
            "6. 最多用 1 个 emoji，也可以不用。\n"
            + _STYLE_BLOCK
            + _GROUPCHAT_BLOCK
            + _banned_section()
            + humanstyle.style_block()
            + _avoid_section(avoid)
            + format_block(True)
        )
    if proactive:
        base += _PROACTIVE_TAIL
    if insist:
        base += _INSIST_TAIL
    return base


def chat_system_prompt(cfg, avoid=(), comfort: bool = False) -> str:
    """用户直接跟它说话（打字/语音）时的系统提示词：这一轮必须接话，不许沉默。

    comfort=True 是他这一句在诉苦（见 humanstyle.needs_comfort）：
    那一轮不谈画面、不讲道理，只安慰 + 抱抱（见 _COMFORT_TAIL）。
    """
    if cfg.system_prompt.strip():
        base = cfg.system_prompt.strip()
    else:
        p = cfg.persona
        base = (
            f"你叫「{p.name}」，是一个住在用户电脑屏幕边上的陪伴小精灵。性格：{p.style}。\n"
            "现在用户**直接跟你说话**（可能是打字，也可能是语音识别出来的文字，就在「用户跟你说」那一段），"
            "你要像朋友那样接话，而不是在旁边自言自语。\n"
            + _STYLE_BLOCK
            + _GROUPCHAT_BLOCK
            + _banned_section()
            + humanstyle.chat_block()
            + _avoid_section(avoid)
            + "接话的规矩：\n"
            f"1. 必须正面回应他说的那件事，1~2 句，总共不超过 {int(getattr(cfg.chat, 'max_chars', 90))} 个字。\n"
            "2. 他问你什么就答什么，别转移话题；不知道就直说不知道，别编数据、别编剧情。\n"
            "3. 他嘴里的「你」指的是**你自己**（这个桌宠），不是画面里的人、也不是他主人——"
            "他问「你在干嘛」，就用「我」回你自己在干嘛，别把问句原样抛回去。\n"
            "4. 屏幕上的画面是背景，不是这一轮的主题：他要是没聊到画面，就别主动往上扯；"
            "只有他明确问视频里的事，才拿你看到的细节答。\n"
            "5. 可以反问他一句，让话头接得下去。\n"
            "6. 这一轮是你**回他**（他先开的口），不是你自己找话说；"
            "不许沉默、不许只回 [沉默] 或者一个表情。\n"
            "7. 他要是问视频里的内容，就翻上面【你刚看完的视频】【看片记录】，"
            "拿里面的具体细节答（谁、说了什么、那句台词是啥），别糊弄成「挺有意思的」。\n"
            "8. 说话方式就是两个朋友一块看视频时的互相吐槽：可以起哄、可以拆台、可以说自己笑死，"
            "但别做总结陈词，别像在给视频写简介。\n"
            "9. 他要是让你夸他、要情绪价值，就痛快夸：挑具体的事夸（他最近在忙什么、看什么），"
            "一句到两句，不许「不过」「但是」，不许先夸后贬、不许往回找补。\n"
            + format_block(False)
        )
    if comfort:
        base += _COMFORT_TAIL
    return base



    
