def _build(raw: str) -> Tuple[Dict[str, str], int]:
    """把「繁简」串拆成对照表，顺手数一下有几条写坏了（长度不等于 2）。

    换行和空格都当分隔符用（表是按行排的，行尾不一定要写逗号）。
    """
    table: Dict[str, str] = {}
    bad = 0
    for item in raw.replace("\n", ",").replace(" ", ",").split(","):
        if not item:
            continue
        if len(item) != 2:
            bad += 1
            continue
        table[item[0]] = item[1]
    return table, bad


_T2S, _T2S_BAD = _build(_T2S_RAW)
_TRANS = str.maketrans(_T2S)


def to_simplified(text: str) -> str:
    """把整句里的繁体字换成简体；本来就是简体（或没有繁体字）就原样返回。

    绝大多数句子走的是快路（一个繁体字都没有，直接返回），所以这个函数
    塞在每句台词都要过的链路上也不心疼。
    """
    line = text or ""
    if not line:
        return line
    if not any(ch in _T2S for ch in line):
        return line
    return line.translate(_TRANS)


def table_size() -> int:
    """对照表收了多少个字（日志和 smoke test 用）。"""
    return len(_T2S)


def bad_entries() -> int:
    """写坏了几条（正常必须是 0；smoke test 会盯着它）。"""
    return _T2S_BAD
